
def calculate_average(a: float, b: float, c: float) -> float:
    """
    Calculate the average of three numbers.

    Args:
        a: First number
        b: Second number
        c: Third number

    Returns:
        Arithmetic average of the three numbers.
    """

    # Add all three numbers.
    total = a + b + c

    # Divide by 3 to calculate the average.
    average = total / 3

    # Return the calculated result.
    return average
